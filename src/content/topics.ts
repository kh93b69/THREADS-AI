/**
 * Детерминированный выбор темы: без БД и без состояния в памяти.
 * Один и тот же слот одного и того же дня всегда даёт одну и ту же тему,
 * поэтому перезапуск контейнера ничего не ломает и не плодит дубли.
 */
export function pickTopic(date: Date, slotIndex: number, slotsPerDay: number): Topic {
  if (TOPICS.length === 0) throw new Error("Контент-план пуст: заполни TOPICS в src/content/topics.ts");

  const dayNumber = Math.floor(date.getTime() / 86_400_000);
  const sequence = dayNumber * Math.max(slotsPerDay, 1) + slotIndex;
  const topic = TOPICS[((sequence % TOPICS.length) + TOPICS.length) % TOPICS.length]
;
  // noUncheckedIndexedAccess: индекс уже нормализован по длине, но TS этого не знает.
  if (!topic) throw new Error("Не удалось выбрать тему из контент-плана");
  return topic;
}
