/**
 * Контент-план. Это единственный файл, который нужно править, чтобы
 * поменять то, о чём бот постит. Правишь список → пушишь → Railway редеплоит.
 *
 * Темы берутся по кругу, строго по порядку: список не повторится,
 * пока не кончится. Так что порядок = порядок выхода постов.
 */
export interface Topic {
  /** О чём пост. Чем конкретнее, тем лучше текст. */
  topic: string;
  /** Тон именно этого поста. Если не задан — берётся DEFAULT_TONE. */
  tone?: string;
  /** Чем заканчивается пост. Если не задан — без призыва. */
  cta?: CallToAction;
  /** Формат. По умолчанию обычный пост на 400-500 символов. */
  format?: PostFormat;
}

/**
 * Формат поста.
 * "normal" — развёрнутый пост с мыслью и аргументом.
 * "short"  — наблюдение из разговора с клиентом в 2-3 предложения,
 *            заканчивается вопросом в зал. Такие собирают комментарии
 *            лучше длинных: отвечать легко и есть что рассказать.
 */
export type PostFormat = "normal" | "short";

