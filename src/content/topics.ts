/** Каждый третий пост — короткий. Чаще приедается, реже не набирает комментариев. */
const SHORT_EVERY = 3;

const NORMAL_TOPICS = TOPICS.filter((topic) => topic.format !== "short");
const SHORT_TOPICS = TOPICS.filter((topic) => topic.format === "short");

/**
 * Детерминированный выбор темы: без БД и без состояния в памяти.
 * Один и тот же слот одного и того же дня всегда даёт одну и ту же тему,
 * поэтому перезапуск контейнера ничего не ломает и не плодит дубли.
 *
 * Длинные и короткие посты идут не подряд, а чередуются: иначе десять
 * коротких подряд выглядят как другой аккаунт.
 */
export function pickTopic(date: Date, slotIndex: number, slotsPerDay: number): Topic {
  if (TOPICS.length === 0) throw new Error("Контент-план пуст: заполни TOPICS в src/content/topics.ts");

  const dayNumber = Math.floor(date.getTime() / 86_400_000);
  const sequence = dayNumber * Math.max(slotsPerDay, 1) + slotIndex;

  const isShortSlot = SHORT_TOPICS.length > 0 && mod(sequence, SHORT_EVERY) === SHORT_EVERY - 1;
  const pool = isShortSlot ? SHORT_TOPICS : NORMAL_TOPICS;

  // Сколько раз этот пул уже использовался до текущего номера в очереди.
  const used = isShortSlot
    ? Math.floor(sequence / SHORT_EVERY)
    : sequence - Math.floor((sequence + 1) / SHORT_EVERY);

  const topic = pool[mod(used, pool.length)];
  if (!topic) throw new Error("Не удалось выбрать тему из контент-плана");
  return topic;
}

/** Остаток от деления, корректный для отрицательных чисел. */
function mod(value: number, size: number): number {
  return ((value % size) + size) % size;
}
